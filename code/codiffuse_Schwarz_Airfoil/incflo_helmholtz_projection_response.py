"""Audited homogeneous-response kernels for the native Airfoil step.

The native corpus is generated by incflo with constant density, implicit
component diffusion, and a nodal projection.  With convection, Brinkman
forcing, and the time-n pressure gradient held in the particular right-hand
side, the linear response to an artificial velocity trace is

    (I - dt*nu*Laplacian) dw = 0,
    dt*D*G dp = D*dw,
    du = dw - dt*G*dp.

The first projection below uses the exact cell-from-node gradient from AMReX
and its Euclidean adjoint.  It is useful as a projection-closure diagnostic,
but it is not the complete AMReX nodal projector: AMReX solves a Q1 weak
nine-point nodal Laplacian and treats prescribed normal velocity as an
``inflow`` boundary contribution.  The source-audited weak operator and its
inflow right-hand side are therefore exposed separately below.  Both variants
are matrix-free and batched across local crops.

The module also exposes the incompressible compatibility condition for a
prescribed velocity trace and a minimum-norm, target-free projection onto the
zero-net-flux trace plane.

This module is initially a gated numerical branch.  Existing checkpoints keep
their historical response until a new particular solution is relabelled and
trained against this exact response contract.
"""

from __future__ import annotations

from dataclasses import dataclass
import math

import numpy as np
import torch

from .discrete_modified_stokes_response import (
    _batch_inner,
    _edge_mask,
    _gradient_energy_operator,
    _velocity_face_values,
)


Tensor = torch.Tensor
FACE_NORMALS = ((0.0, -1.0), (0.0, 1.0), (-1.0, 0.0), (1.0, 0.0))


