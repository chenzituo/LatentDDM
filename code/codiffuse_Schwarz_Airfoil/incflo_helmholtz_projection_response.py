def _validate_port(port: Tensor, roles: Tensor) -> None:
    if port.ndim != 4 or port.shape[1] != 8:
        raise ValueError("velocity port must have shape B,8,H,W")
    if roles.shape != (port.shape[0], 4, *port.shape[-2:]):
        raise ValueError("face roles must have shape B,4,H,W")


def physical_face_velocity(port: Tensor, state_std: Tensor) -> Tensor:
    """Return physical four-face velocity blocks from a standardized port."""
    if port.ndim != 4 or port.shape[1] != 8:
        raise ValueError("velocity port must have shape B,8,H,W")
    scale = torch.as_tensor(
        state_std, device=port.device, dtype=port.dtype,
    ).flatten()
    if scale.numel() < 2 or bool(torch.any(scale[:2] <= 0.0)):
        raise ValueError("state_std must contain positive u and v scales")
    return port.reshape(port.shape[0], 4, 2, *port.shape[-2:]) * scale[
        :2
    ].reshape(1, 1, 2, 1, 1)


def dirichlet_flux_compatibility(
    port: Tensor,
    roles: Tensor,
    *,
    state_std: Tensor,
    dx: float,
) -> dict[str, Tensor]:
    """Measure net and absolute normal flux for every represented tile trace."""
    _validate_port(port, roles)
    if not np.isfinite(dx) or dx <= 0.0:
        raise ValueError("dx must be positive")
    velocity = physical_face_velocity(port, state_std)
    normals = port.new_tensor(FACE_NORMALS).reshape(1, 4, 2, 1, 1)
    normal = (velocity * normals).sum(2) * roles
    net = float(dx) * normal.sum((1, 2, 3))
    absolute = float(dx) * normal.abs().sum((1, 2, 3))
    relative = torch.where(
        absolute > 0.0, net.abs() / absolute.clamp_min(1.0e-30),
        torch.zeros_like(absolute),
    )
    return {
        "net_flux": net,
        "absolute_normal_flux": absolute,
        "relative_imbalance": relative,
        "active": absolute > 0.0,
    }


def project_port_to_zero_net_flux(
    port: Tensor,
    roles: Tensor,
    *,
    state_std: Tensor,
    dx: float,
) -> tuple[Tensor, dict[str, Tensor]]:
    """Apply the minimum physical-L2 correction satisfying zero net flux."""
    diagnostics = dirichlet_flux_compatibility(
        port, roles, state_std=state_std, dx=dx,
    )
    count = roles.sum((1, 2, 3))
    alpha = torch.where(
        count > 0.0,
        -diagnostics["net_flux"] / (float(dx) * count).clamp_min(1.0e-30),
        torch.zeros_like(count),
    )
    normals = port.new_tensor(FACE_NORMALS).reshape(1, 4, 2, 1, 1)
    physical = physical_face_velocity(port, state_std)
    corrected_physical = physical + (
        alpha[:, None, None, None, None] * normals
        * roles[:, :, None]
    )
    scale = torch.as_tensor(
        state_std, device=port.device, dtype=port.dtype,
    ).flatten()[:2]
    corrected = (
        corrected_physical / scale.reshape(1, 1, 2, 1, 1)
    ).reshape_as(port)
    corrected = corrected * roles.repeat_interleave(2, dim=1)
    after = dirichlet_flux_compatibility(
        corrected, roles, state_std=state_std, dx=dx,
    )
    correction = corrected_physical - physical
    base_norm = (physical.square() * roles[:, :, None]).flatten(1).sum(1).sqrt()
    correction_norm = (
        correction.square() * roles[:, :, None]
    ).flatten(1).sum(1).sqrt()
    after.update({
        "correction_relative_l2": torch.where(
            base_norm > 0.0,
            correction_norm / base_norm.clamp_min(1.0e-30),
            torch.zeros_like(base_norm),
        ),
        "correction_physical_l2": correction_norm,
    })
    return corrected, after


def _positive_batch_parameter(
    value: Tensor | float,
    reference: Tensor,
    name: str,
    *,
    allow_zero: bool = False,
) -> Tensor:
    result = torch.as_tensor(
        value, device=reference.device, dtype=reference.dtype,
    ).flatten()
    if result.numel() == 1:
        result = result.expand(reference.shape[0])
    invalid = result < 0.0 if allow_zero else result <= 0.0
    if result.numel() != reference.shape[0] or bool(torch.any(invalid)):
        qualifier = "nonnegative" if allow_zero else "positive"
        raise ValueError(f"{name} must be scalar or crop-aligned and {qualifier}")
    return result


def _matrix_free_cg(
    operator,
    right_hand_side: Tensor,
    *,
    support: Tensor,
    iterations: int,
    tolerance: float,
    projector=None,
) -> tuple[Tensor, Tensor]:
    if iterations <= 0 or not math.isfinite(tolerance) or tolerance <= 0.0:
        raise ValueError("CG iterations and tolerance must be positive")
    rhs = right_hand_side * support
    if projector is not None:
        rhs = projector(rhs)
    rhs_norm = _batch_inner(rhs, rhs).sqrt()
    solution = torch.zeros_like(rhs)
    residual = rhs.clone()
    direction = residual.clone()
    residual_square = _batch_inner(residual, residual)
    threshold = tolerance * rhs_norm.clamp_min(1.0e-30)
    live = rhs_norm > 0.0
    for _ in range(iterations):
        previous_square = residual_square
        applied = operator(direction * support) * support
        if projector is not None:
            applied = projector(applied)
        denominator = _batch_inner(direction, applied)
        safe = live & (denominator > 1.0e-30)
        alpha = torch.where(
            safe,
            residual_square / denominator.clamp_min(1.0e-30),
            torch.zeros_like(denominator),
        )
        solution = solution + alpha[:, None, None, None] * direction
        if projector is not None:
            solution = projector(solution)
        residual = residual - alpha[:, None, None, None] * applied
        if projector is not None:
            residual = projector(residual)
        next_square = _batch_inner(residual, residual)
        next_live = live & (next_square.sqrt() > threshold)
        if not bool(torch.any(next_live)):
            residual_square = next_square
            break
        beta = torch.where(
            next_live,
            next_square / previous_square.clamp_min(1.0e-30),
            torch.zeros_like(next_square),
        )
        direction = residual + beta[:, None, None, None] * direction
        if projector is not None:
            direction = projector(direction)
        residual_square = next_square
        live = next_live
    relative = residual_square.sqrt() / rhs_norm.clamp_min(1.0e-30)
    relative = torch.where(rhs_norm > 0.0, relative, torch.zeros_like(relative))
    return solution * support, relative


def helmholtz_velocity_response(
    boundary_velocity: Tensor,
    boundary_active: Tensor,
    valid: Tensor,
    *,
    diffusive_cfl: Tensor | float,
    iterations: int = 160,
    tolerance: float = 1.0e-7,
) -> tuple[Tensor, Tensor]:
    """Solve ``(I-dt*nu*Laplacian) dw=0`` with a crop-edge trace."""
    if boundary_velocity.ndim != 4 or boundary_velocity.shape[1] != 2:
        raise ValueError("boundary velocity must have shape B,2,H,W")
    if boundary_active.shape != boundary_velocity[:, :1].shape:
        raise ValueError("boundary activity must have shape B,1,H,W")
    if valid.shape != boundary_velocity[:, :1].shape:
        raise ValueError("validity must have shape B,1,H,W")
    work = boundary_velocity.float()
    valid_work = (valid > 0.5).to(work)
    fixed = _edge_mask(valid_work).to(work) * valid_work
    prescribed = work * boundary_active.to(work) * fixed
    free = valid_work * (1.0 - fixed)
    support = free.expand(-1, 2, -1, -1)
    coefficient = _positive_batch_parameter(
        diffusive_cfl, work, "diffusive_cfl", allow_zero=True,
    )[:, None, None, None]

    def operator(value: Tensor) -> Tensor:
        return (
            value * valid_work
            + coefficient * _gradient_energy_operator(value, valid_work)
        )

    right_hand_side = -operator(prescribed) * support
    solution, relative = _matrix_free_cg(
        operator, right_hand_side, support=support,
        iterations=iterations, tolerance=tolerance,
    )
    return ((prescribed + solution) * valid_work).to(boundary_velocity), relative


def nodal_gradient(phi: Tensor, dx: float) -> Tensor:
    """AMReX regular-2D gradient from nodal scalar to cell velocity."""
    if phi.ndim != 4 or phi.shape[1] != 1 or min(phi.shape[-2:]) < 2:
        raise ValueError("nodal scalar must have shape B,1,H+1,W+1")
    if not math.isfinite(dx) or dx <= 0.0:
        raise ValueError("dx must be positive")
    p00 = phi[..., :-1, :-1]
    p10 = phi[..., :-1, 1:]
    p01 = phi[..., 1:, :-1]
    p11 = phi[..., 1:, 1:]
    factor = 0.5 / float(dx)
    return torch.cat((
        factor * (-p00 + p10 - p01 + p11),
        factor * (-p00 - p10 + p01 + p11),
    ), dim=1)


def nodal_gradient_adjoint(velocity: Tensor, dx: float) -> Tensor:
    """Exact Euclidean adjoint of :func:`nodal_gradient`."""
    if velocity.ndim != 4 or velocity.shape[1] != 2:
        raise ValueError("cell velocity must have shape B,2,H,W")
    if not math.isfinite(dx) or dx <= 0.0:
        raise ValueError("dx must be positive")
    factor = 0.5 / float(dx)
    u = velocity[:, 0:1]
    v = velocity[:, 1:2]
    result = velocity.new_zeros(
        velocity.shape[0], 1, velocity.shape[-2] + 1,
        velocity.shape[-1] + 1,
    )
    result[..., :-1, :-1] += factor * (-u - v)
    result[..., :-1, 1:] += factor * (u - v)
    result[..., 1:, :-1] += factor * (-u + v)
    result[..., 1:, 1:] += factor * (u + v)
    return result


def _nodal_validity(valid: Tensor) -> Tensor:
    nodal = valid.new_zeros(
        valid.shape[0], 1, valid.shape[-2] + 1, valid.shape[-1] + 1,
    )
    for ys, xs in (
        (slice(None, -1), slice(None, -1)),
        (slice(None, -1), slice(1, None)),
        (slice(1, None), slice(None, -1)),
        (slice(1, None), slice(1, None)),
    ):
        nodal[..., ys, xs] = torch.maximum(nodal[..., ys, xs], valid)
    return nodal


def nodal_projection_response(
    velocity: Tensor,
    valid: Tensor,
    *,
    dt: Tensor | float,
    dx: float,
    iterations: int = 320,
    tolerance: float = 1.0e-7,
) -> tuple[Tensor, Tensor, Tensor, Tensor, Tensor]:
    """Apply the constant-density regular-grid nodal projection.

    Returns projected velocity, cell pressure, cell pressure gradient,
    relative linear residual, and the before/after nodal-divergence RMS pair.
    """
    if velocity.ndim != 4 or velocity.shape[1] != 2:
        raise ValueError("velocity must have shape B,2,H,W")
    if valid.shape != velocity[:, :1].shape:
        raise ValueError("validity must have shape B,1,H,W")
    valid_work = (valid > 0.5).to(velocity)
    nodal_valid = _nodal_validity(valid_work)
    dt_value = _positive_batch_parameter(dt, velocity, "dt")

    def remove_gauge(value: Tensor) -> Tensor:
        mean = (
            (value * nodal_valid).flatten(1).sum(1)
            / nodal_valid.flatten(1).sum(1).clamp_min(1.0)
        )
        return (value - mean[:, None, None, None]) * nodal_valid

    def operator(value: Tensor) -> Tensor:
        gradient = nodal_gradient(value, dx) * valid_work
        applied = nodal_gradient_adjoint(gradient, dx)
        return remove_gauge(dt_value[:, None, None, None] * applied)

    divergence_before = nodal_gradient_adjoint(
        velocity * valid_work, dx,
    ) * nodal_valid
    right_hand_side = remove_gauge(divergence_before)
    pressure_nodes, relative = _matrix_free_cg(
        operator, right_hand_side, support=nodal_valid,
        iterations=iterations, tolerance=tolerance, projector=remove_gauge,
    )
    pressure_nodes = remove_gauge(pressure_nodes)
    gradient = nodal_gradient(pressure_nodes, dx) * valid_work
    projected = (
        velocity - dt_value[:, None, None, None] * gradient
    ) * valid_work
    divergence_after = nodal_gradient_adjoint(projected, dx) * nodal_valid
    pressure_cell = 0.25 * (
        pressure_nodes[..., :-1, :-1]
        + pressure_nodes[..., :-1, 1:]
        + pressure_nodes[..., 1:, :-1]
        + pressure_nodes[..., 1:, 1:]
    ) * valid_work
    pressure_mean = (
        (pressure_cell * valid_work).flatten(1).sum(1)
        / valid_work.flatten(1).sum(1).clamp_min(1.0)
    )
    pressure_cell = (
        pressure_cell - pressure_mean[:, None, None, None]
    ) * valid_work
    before_rms = divergence_before.flatten(1).square().mean(1).sqrt()
    after_rms = divergence_after.flatten(1).square().mean(1).sqrt()
    return projected, pressure_cell, gradient, relative, torch.stack((
        before_rms, after_rms,
    ), dim=1)


def amrex_q1_nodal_stiffness(
    phi: Tensor,
    valid_cells: Tensor,
    *,
    dx: float,
) -> Tensor:
    """Apply the positive Q1 stiffness underlying regular 2-D MLNodeLaplacian.

    AMReX stores the negative of this operator.  On a uniform square grid its
    interior stencil has center ``8/3`` and all eight neighbors ``-1/3``,
    scaled by ``dx**-2``.  Element assembly gives the natural Neumann/inflow
    boundary stencil without inventing pressure values outside the crop.
    """
    if phi.ndim != 4 or phi.shape[1] != 1 or min(phi.shape[-2:]) < 2:
        raise ValueError("nodal scalar must have shape B,1,H+1,W+1")
    if valid_cells.shape != (
        phi.shape[0], 1, phi.shape[-2] - 1, phi.shape[-1] - 1,
    ):
        raise ValueError("cell validity is not aligned with the nodal scalar")
    if not math.isfinite(dx) or dx <= 0.0:
        raise ValueError("dx must be positive")
    element = (valid_cells > 0.5).to(phi)
    p00 = phi[..., :-1, :-1]
    p10 = phi[..., :-1, 1:]
    p01 = phi[..., 1:, :-1]
    p11 = phi[..., 1:, 1:]
    factor = element / (6.0 * float(dx * dx))
    result = torch.zeros_like(phi)
    result[..., :-1, :-1] += factor * (
        4.0 * p00 - p10 - p01 - 2.0 * p11
    )
    result[..., :-1, 1:] += factor * (
        -p00 + 4.0 * p10 - 2.0 * p01 - p11
    )
    result[..., 1:, :-1] += factor * (
        -p00 - 2.0 * p10 + 4.0 * p01 - p11
    )
    result[..., 1:, 1:] += factor * (
        -2.0 * p00 - p10 - p01 + 4.0 * p11
    )
    return result


def _add_face_flux_to_nodes(
    destination: Tensor,
    values: Tensor,
    *,
    axis: int,
    side: int,
    dx: float,
) -> None:
    """Assemble one cell-face normal flux into Q1 boundary nodes in place."""
    if destination.ndim != 4 or destination.shape[1] != 1:
        raise ValueError("destination must be a nodal scalar")
    if values.ndim != 2 or values.shape[0] != destination.shape[0]:
        raise ValueError("face values must be a batched vector")
    sign = -1.0 if side == 0 else 1.0
    weighted = values * (0.5 * sign / float(dx))
    if axis == 0:
        if values.shape[1] != destination.shape[-2] - 1:
            raise ValueError("vertical face length is inconsistent")
        column = 0 if side == 0 else destination.shape[-1] - 1
        destination[:, 0, :-1, column] += weighted
        destination[:, 0, 1:, column] += weighted
    elif axis == 1:
        if values.shape[1] != destination.shape[-1] - 1:
            raise ValueError("horizontal face length is inconsistent")
        row = 0 if side == 0 else destination.shape[-2] - 1
        destination[:, 0, row, :-1] += weighted
        destination[:, 0, row, 1:] += weighted
    else:
        raise ValueError("axis must be x or y")


def amrex_inflow_weak_divergence(
    velocity: Tensor,
    face_velocity: Tensor,
    face_roles: Tensor,
    valid_cells: Tensor,
    *,
    dx: float,
) -> Tensor:
    """Reproduce the regular 2-D ``mlndlap_divu`` inflow right-hand side.

    ``face_velocity`` contains four physical ``(u,v)`` blocks.  At an inflow
    face AMReX excludes transverse ghost velocity from the nodal divergence;
    consequently only the represented normal component enters here.
    """
    if velocity.ndim != 4 or velocity.shape[1] != 2:
        raise ValueError("velocity must have shape B,2,H,W")
    if face_velocity.shape != (
        velocity.shape[0], 4, 2, *velocity.shape[-2:],
    ):
        raise ValueError("face velocity must contain four physical blocks")
    if face_roles.shape != (
        velocity.shape[0], 4, *velocity.shape[-2:],
    ):
        raise ValueError("face roles are not velocity aligned")
    if valid_cells.shape != velocity[:, :1].shape:
        raise ValueError("cell validity is not velocity aligned")
    if not math.isfinite(dx) or dx <= 0.0:
        raise ValueError("dx must be positive")
    valid = (valid_cells > 0.5).to(velocity)
    # AMReX's divergence convention is the negative Euclidean adjoint of its
    # cell-from-node gradient.  The ghost-normal terms below supply the
    # boundary part that is absent from the valid-cell adjoint.
    result = -nodal_gradient_adjoint(velocity * valid, dx)
    bottom = face_velocity[:, 0, 1, 0, :] * face_roles[:, 0, 0, :]
    top = face_velocity[:, 1, 1, -1, :] * face_roles[:, 1, -1, :]
    left = face_velocity[:, 2, 0, :, 0] * face_roles[:, 2, :, 0]
    right = face_velocity[:, 3, 0, :, -1] * face_roles[:, 3, :, -1]
    _add_face_flux_to_nodes(result, left, axis=0, side=0, dx=dx)
    _add_face_flux_to_nodes(result, right, axis=0, side=1, dx=dx)
    _add_face_flux_to_nodes(result, bottom, axis=1, side=0, dx=dx)
    _add_face_flux_to_nodes(result, top, axis=1, side=1, dx=dx)
    return result * _nodal_validity(valid)


def amrex_inflow_nodal_projection_response(
    velocity: Tensor,
    boundary_port: Tensor,
    face_roles: Tensor,
    valid_cells: Tensor,
    *,
    state_std: Tensor,
    dt: Tensor | float,
    dx: float,
    iterations: int = 320,
    tolerance: float = 1.0e-7,
) -> tuple[Tensor, Tensor, Tensor, AmrexNodalProjectionDiagnostics]:
    """Apply the source-audited regular 2-D approximate nodal projection.

    This mirrors incflo/AMReX's regular-grid contracts: a Q1 weak nodal
    Laplacian, an inflow RHS that sees only prescribed normal ghost velocity,
    the AMReX cell-centered gradient, and one pressure gauge.  The prescribed
    face data are an external boundary state and are therefore not overwritten
    after projection.
    """
    _validate_port(boundary_port, face_roles)
    if velocity.ndim != 4 or velocity.shape[1] != 2:
        raise ValueError("velocity must have shape B,2,H,W")
    if valid_cells.shape != velocity[:, :1].shape:
        raise ValueError("cell validity is not velocity aligned")
    scale = torch.as_tensor(
        state_std, device=velocity.device, dtype=velocity.dtype,
    ).flatten()
    if scale.numel() < 2 or bool(torch.any(scale[:2] <= 0.0)):
        raise ValueError("state_std must contain positive velocity scales")
    dt_value = _positive_batch_parameter(dt, velocity, "dt")
    physical_faces = physical_face_velocity(boundary_port, scale)
    valid = (valid_cells > 0.5).to(velocity)
    nodal_valid = _nodal_validity(valid)

    def remove_gauge(value: Tensor) -> Tensor:
        denominator = nodal_valid.flatten(1).sum(1).clamp_min(1.0)
        mean = (value * nodal_valid).flatten(1).sum(1) / denominator
        return (value - mean[:, None, None, None]) * nodal_valid

    raw_rhs = amrex_inflow_weak_divergence(
        velocity, physical_faces, face_roles, valid, dx=dx,
    )
    rhs = remove_gauge(raw_rhs)
    raw_norm = _batch_inner(raw_rhs, raw_rhs).sqrt()
    solvability_change = _batch_inner(raw_rhs - rhs, raw_rhs - rhs).sqrt()
    solvability_relative = torch.where(
        raw_norm > 0.0,
        solvability_change / raw_norm.clamp_min(1.0e-30),
        torch.zeros_like(raw_norm),
    )

    def operator(value: Tensor) -> Tensor:
        applied = amrex_q1_nodal_stiffness(value, valid, dx=dx)
        return remove_gauge(dt_value[:, None, None, None] * applied)

    # AMReX stores L=-K and solves L phi=div(u); hence the positive stiffness
    # solve has right-hand side -div(u).
    pressure_nodes, relative = _matrix_free_cg(
        operator, -rhs, support=nodal_valid,
        iterations=iterations, tolerance=tolerance, projector=remove_gauge,
    )
    pressure_nodes = remove_gauge(pressure_nodes)
    gradient = nodal_gradient(pressure_nodes, dx) * valid
    projected = (
        velocity - dt_value[:, None, None, None] * gradient
    ) * valid
    after = amrex_inflow_weak_divergence(
        projected, physical_faces, face_roles, valid, dx=dx,
    )
    before_rms = raw_rhs.flatten(1).square().mean(1).sqrt()
    after_rms = after.flatten(1).square().mean(1).sqrt()
    pressure_cell = 0.25 * (
        pressure_nodes[..., :-1, :-1]
        + pressure_nodes[..., :-1, 1:]
        + pressure_nodes[..., 1:, :-1]
        + pressure_nodes[..., 1:, 1:]
    ) * valid
    pressure_mean = (
        (pressure_cell * valid).flatten(1).sum(1)
        / valid.flatten(1).sum(1).clamp_min(1.0)
    )
    pressure_cell = (
        pressure_cell - pressure_mean[:, None, None, None]
    ) * valid
    return projected, pressure_cell, gradient, AmrexNodalProjectionDiagnostics(
        linear_relative_residual=relative,
        rhs_solvability_correction_relative_l2=solvability_relative,
        weak_divergence_before_rms=before_rms,
        weak_divergence_after_rms=after_rms,
    )


def source_audited_helmholtz_nodal_response(
    boundary_defect: Tensor,
    face_roles: Tensor,
    valid: Tensor,
    *,
    state_std: Tensor,
    projection_std: Tensor,
    dt: Tensor | float,
    dx: float,
    viscosity: Tensor | float,
    flux_compatibility: bool = True,
    helmholtz_iterations: int = 160,
    projection_iterations: int = 320,
    tolerance: float = 1.0e-7,
) -> tuple[Tensor, SourceAuditedResponseDiagnostics]:
    """Compose the overlap Helmholtz solve with the source-audited projector.

    The overlap edge remains a strong value in the diffusion solve.  During
    projection the same port is treated as AMReX ``inflow`` ghost data, so its
    normal flux enters the weak RHS and is not overwritten after projection.
    """
    _validate_port(boundary_defect, face_roles)
    state_scale = torch.as_tensor(
        state_std, device=boundary_defect.device, dtype=boundary_defect.dtype,
    ).flatten()
    projection_scale = torch.as_tensor(
        projection_std, device=boundary_defect.device,
        dtype=boundary_defect.dtype,
    ).flatten()
    if (
        state_scale.numel() != 3 or projection_scale.numel() != 2
        or bool(torch.any(state_scale <= 0.0))
        or bool(torch.any(projection_scale <= 0.0))
    ):
        raise ValueError("state and projection scales have invalid channels")
    original_flux = dirichlet_flux_compatibility(
        boundary_defect, face_roles, state_std=state_scale, dx=dx,
    )
    if flux_compatibility:
        compatible_port, compatibility = project_port_to_zero_net_flux(
            boundary_defect, face_roles, state_std=state_scale, dx=dx,
        )
    else:
        compatible_port = boundary_defect
        compatibility = {
            "correction_relative_l2": boundary_defect.new_zeros(
                boundary_defect.shape[0]
            )
        }
    normalized_boundary, active = _velocity_face_values(
        compatible_port, face_roles,
    )
    boundary_velocity = normalized_boundary * state_scale[:2].reshape(
        1, 2, 1, 1,
    )
    dt_value = _positive_batch_parameter(dt, boundary_velocity, "dt")
    viscosity_value = _positive_batch_parameter(
        viscosity, boundary_velocity, "viscosity", allow_zero=True,
    )
    velocity_star, helmholtz_residual = helmholtz_velocity_response(
        boundary_velocity, active, valid,
        diffusive_cfl=viscosity_value * dt_value / float(dx * dx),
        iterations=helmholtz_iterations, tolerance=tolerance,
    )
    projected, pressure, gradp, projection = (
        amrex_inflow_nodal_projection_response(
            velocity_star, compatible_port, face_roles, valid,
            state_std=state_scale, dt=dt_value, dx=dx,
            iterations=projection_iterations, tolerance=tolerance,
        )
    )
    standardized = torch.cat((
        projected / state_scale[:2].reshape(1, 2, 1, 1),
        pressure / state_scale[2].reshape(1, 1, 1, 1),
        gradp / projection_scale.reshape(1, 2, 1, 1),
    ), dim=1)
    return standardized, SourceAuditedResponseDiagnostics(
        helmholtz_relative_residual=helmholtz_residual,
        projection_linear_relative_residual=(
            projection.linear_relative_residual
        ),
        rhs_solvability_correction_relative_l2=(
            projection.rhs_solvability_correction_relative_l2
        ),
        relative_boundary_flux_imbalance=original_flux["relative_imbalance"],
        boundary_flux_projection_relative_l2=compatibility[
            "correction_relative_l2"
        ],
        weak_divergence_before_projection_rms=(
            projection.weak_divergence_before_rms
        ),
        weak_divergence_after_projection_rms=(
            projection.weak_divergence_after_rms
        ),
    )


def incflo_helmholtz_nodal_response(
    boundary_defect: Tensor,
    face_roles: Tensor,
    valid: Tensor,
    *,
    state_std: Tensor,
    projection_std: Tensor,
    dt: Tensor | float,
    dx: float,
    viscosity: Tensor | float,
    flux_compatibility: bool = True,
    helmholtz_iterations: int = 160,
    projection_iterations: int = 320,
    tolerance: float = 1.0e-7,
) -> tuple[Tensor, IncfloResponseDiagnostics]:
    """Return standardized ``du,dv,dp,dgpx,dgpy`` response channels."""
    _validate_port(boundary_defect, face_roles)
    state_scale = torch.as_tensor(
        state_std, device=boundary_defect.device, dtype=boundary_defect.dtype,
    ).flatten()
    projection_scale = torch.as_tensor(
        projection_std, device=boundary_defect.device,
        dtype=boundary_defect.dtype,
    ).flatten()
    if (
        state_scale.numel() != 3 or projection_scale.numel() != 2
        or bool(torch.any(state_scale <= 0.0))
        or bool(torch.any(projection_scale <= 0.0))
    ):
        raise ValueError("state and projection scales have invalid channels")
    original_flux = dirichlet_flux_compatibility(
        boundary_defect, face_roles, state_std=state_scale, dx=dx,
    )
    if flux_compatibility:
        compatible_port, compatibility = project_port_to_zero_net_flux(
            boundary_defect, face_roles, state_std=state_scale, dx=dx,
        )
    else:
        compatible_port = boundary_defect
        compatibility = {
            "correction_relative_l2": boundary_defect.new_zeros(
                boundary_defect.shape[0]
            )
        }
    normalized_boundary, active = _velocity_face_values(
        compatible_port, face_roles,
    )
    boundary_velocity = normalized_boundary * state_scale[:2].reshape(
        1, 2, 1, 1,
    )
    dt_value = _positive_batch_parameter(dt, boundary_velocity, "dt")
    viscosity_value = _positive_batch_parameter(
        viscosity, boundary_velocity, "viscosity", allow_zero=True,
    )
    velocity_star, helmholtz_residual = helmholtz_velocity_response(
        boundary_velocity, active, valid,
        diffusive_cfl=viscosity_value * dt_value / float(dx * dx),
        iterations=helmholtz_iterations, tolerance=tolerance,
    )
    projected, pressure, gradp, projection_residual, divergence = (
        nodal_projection_response(
            velocity_star, valid, dt=dt_value, dx=dx,
            iterations=projection_iterations, tolerance=tolerance,
        )
    )
    valid_work = (valid > 0.5).to(projected)
    fixed = _edge_mask(valid_work).to(projected) * valid_work
    projected_with_trace = (
        projected * (1.0 - fixed)
        + boundary_velocity * active.to(projected) * fixed
    ) * valid_work
    nodal_valid = _nodal_validity(valid_work)
    divergence_after_trace = nodal_gradient_adjoint(
        projected_with_trace, dx,
    ) * nodal_valid
    divergence_after_trace_rms = (
        divergence_after_trace.flatten(1).square().mean(1).sqrt()
    )
    standardized = torch.cat((
        projected_with_trace / state_scale[:2].reshape(1, 2, 1, 1),
        pressure / state_scale[2].reshape(1, 1, 1, 1),
        gradp / projection_scale.reshape(1, 2, 1, 1),
    ), dim=1)
    return standardized, IncfloResponseDiagnostics(
        helmholtz_relative_residual=helmholtz_residual,
        projection_relative_residual=projection_residual,
        relative_boundary_flux_imbalance=original_flux["relative_imbalance"],
        boundary_flux_projection_relative_l2=compatibility[
            "correction_relative_l2"
        ],
        divergence_before_projection_rms=divergence[:, 0],
        divergence_after_projection_rms=divergence[:, 1],
        divergence_after_trace_rms=divergence_after_trace_rms,
    )
